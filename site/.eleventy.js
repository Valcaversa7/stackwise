const path = require("node:path");

const SRC = "src";
const OUT = "dist";

/* Strip HTML to plain text — used by reading time, excerpts and the
   search index. Code blocks are dropped so they don't inflate counts. */
function stripTags(html = "") {
  return String(html)
    .replace(/<pre[\s\S]*?<\/pre>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/&[a-z#0-9]+;/gi, " ")
    .replace(/\s+/g, " ")
    .trim();
}


module.exports = function (eleventyConfig) {
  /* ------------------------------------------------------------------ *
   * Passthrough: static assets are copied verbatim (no build cost)
   * ------------------------------------------------------------------ */
  eleventyConfig.addPassthroughCopy({ [`${SRC}/assets`]: "assets" });
  eleventyConfig.addPassthroughCopy({ [`${SRC}/favicon.svg`]: "favicon.svg" });
  eleventyConfig.addPassthroughCopy({ [`${SRC}/site.webmanifest`]: "site.webmanifest" });
  // /ads.txt is generated by src/ads.njk so it can pick up the real
  // publisher line from src/_data/site.js.

  /* ------------------------------------------------------------------ *
   * Content collections
   * ------------------------------------------------------------------ */
  eleventyConfig.addCollection("posts", (api) =>
    api
      .getFilteredByGlob(`${SRC}/posts/*.md`)
      .filter((p) => !p.data.draft)
      .sort((a, b) => b.date - a.date)
  );

  // "What's New" feed (/whats-new/): posts flagged with a `news` tag,
  // newest first. The page features the first entry and falls back to
  // nothing (the latest-articles grid still shows) when there is none.
  eleventyConfig.addCollection("newsPosts", (api) =>
    api
      .getFilteredByGlob(`${SRC}/posts/*.md`)
      .filter((p) => !p.data.draft && (p.data.tags || []).includes("news"))
      .sort((a, b) => b.date - a.date)
  );

  // Category hub pages (/guides/, /tutorials/, /reviews/) declare their key.
  eleventyConfig.addCollection("categoryPages", (api) =>
    api
      .getFilteredByGlob(`${SRC}/pages/*.md`)
      .filter((p) => p.data.categoryKey)
      .sort((a, b) => a.data.order - b.data.order)
  );

  /**
   * Hub metadata for the archive pages: the three category hubs plus an
   * `all` entry that powers /blog/. Category templates import this with
   * `eleventyImport` and pick their own entry, so each hub is independent.
   */
  eleventyConfig.addCollection("hubMeta", () => [
    {
      key: "all",
      title: "All articles",
      description:
        "Every guide, tutorial and review we have published, newest first. Narrow it down with the category hubs, the topic cloud in the sidebar, or the search box in the header.",
    },
    ...require("./src/_data/categories"),
  ]);

  // Every category actually used by a post, with counts.
  eleventyConfig.addCollection("categoryIndex", (api) => {
    const posts = api
      .getFilteredByGlob(`${SRC}/posts/*.md`)
      .filter((p) => !p.data.draft);
    const map = new Map();
    for (const p of posts) {
      const key = p.data.categoryKey || "guides";
      const entry = map.get(key) || { key, title: p.data.category || key, count: 0, posts: [] };
      entry.count += 1;
      entry.posts.push(p);
      map.set(key, entry);
    }
    return [...map.values()]
      .map((e) => ({ ...e, posts: e.posts.sort((a, b) => b.date - a.date) }))
      .sort((a, b) => b.count - a.count);
  });

  // Tag cloud for the sidebar / archive.
  eleventyConfig.addCollection("tagIndex", (api) => {
    const posts = api
      .getFilteredByGlob(`${SRC}/posts/*.md`)
      .filter((p) => !p.data.draft);
    const map = new Map();
    for (const p of posts) {
      for (const tag of p.data.tags || []) {
        if (tag === "post") continue;
        const entry = map.get(tag) || { tag, count: 0, posts: [] };
        entry.count += 1;
        entry.posts.push(p);
        map.set(tag, entry);
      }
    }
    return [...map.values()].sort((a, b) => b.count - a.count || a.tag.localeCompare(b.tag));
  });

  /* ------------------------------------------------------------------ *
   * Template filters that need the post list
   * ------------------------------------------------------------------ */
  const allPosts = (collections) => (collections && collections.posts) || [];

  /**
   * Reading time, computed once per template render. Implemented as a filter
   * rather than a function-style collection so templates stay declarative:
   *   {% for post in collections.posts | recent(4) %}
   */
  eleventyConfig.addFilter("recent", (collections, limit = 6, offset = 0) =>
    allPosts(collections).slice(offset, offset + limit)
  );

  /** Older / newer neighbours for the post footer pager. */
  eleventyConfig.addFilter("neighbours", (collections, post) => {
    const all = allPosts(collections);
    const i = all.findIndex((p) => p.url === (post.url || post));
    if (i === -1) return { older: null, newer: null };
    return { older: all[i + 1] || null, newer: all[i - 1] || null };
  });

  /**
   * Related posts: most shared tags first, self excluded.
   *
   * Takes the tag list explicitly rather than reading `page.data`, because
   * front matter is not merged onto `page` in Eleventy 3 — a layout has to
   * pass what it already has in scope.
   */
  eleventyConfig.addFilter("relatedTo", (collections, tags, excludeUrl, limit = 3) => {
    const mine = new Set(tags || []);
    if (!mine.size) return [];
    return allPosts(collections)
      .filter((p) => p.url !== excludeUrl)
      .map((p) => ({
        p,
        score: ((p.data && p.data.tags) || []).filter((t) => mine.has(t)).length,
      }))
      .filter((r) => r.score > 0)
      .sort((a, b) => b.score - a.score || b.p.date - a.p.date)
      .slice(0, limit)
      .map((r) => r.p);
  });

  /** Count of posts in a category key (sidebar badges). */
  eleventyConfig.addFilter("countIn", (collections, key) =>
    allPosts(collections).filter((p) => p.data.categoryKey === key).length
  );

  /* ------------------------------------------------------------------ *
   * Filters
   * ------------------------------------------------------------------ */
  const MONTHS = [
    "January", "February", "March", "April", "May", "June",
    "July", "August", "September", "October", "November", "December",
  ];

  eleventyConfig.addFilter("readableDate", (value) => {
    const d = new Date(value);
    return `${MONTHS[d.getUTCMonth()]} ${d.getUTCDate()}, ${d.getUTCFullYear()}`;
  });

  eleventyConfig.addFilter("shortDate", (value) => {
    const d = new Date(value);
    return `${MONTHS[d.getUTCMonth()].slice(0, 3)} ${d.getUTCDate()}`;
  });

  eleventyConfig.addFilter("isoDate", (value) => new Date(value).toISOString());

  eleventyConfig.addFilter("year", () => new Date().getFullYear());

  eleventyConfig.addFilter("readingTime", (content) => {
    const words = stripTags(content).split(/\s+/).filter(Boolean).length;
    const minutes = Math.max(1, Math.round(words / 225));
    return `${minutes} min read`;
  });

  eleventyConfig.addFilter("wordCount", (content) =>
    stripTags(content).split(/\s+/).filter(Boolean).length
  );

  eleventyConfig.addFilter("plainText", (content, len) => {
    const text = stripTags(content);
    if (!len) return text;
    if (text.length <= len) return text;
    const cut = text.slice(0, len);
    return `${cut.slice(0, Math.max(cut.lastIndexOf(" "), len - 20))}…`;
  });

  eleventyConfig.addFilter("absoluteUrl", (value, base) =>
    new URL(value, base).toString()
  );

  /**
   * Serialize a value as JSON that is safe to embed inside a <script> tag:
   * `<` is escaped so a literal `</script>` in the content cannot close it.
   */
  eleventyConfig.addFilter("jsonLd", (value) =>
    JSON.stringify(value).replace(/</g, "\\u003c")
  );

  eleventyConfig.addFilter("jsonify", (value) =>
    JSON.stringify(value).replace(/</g, "\\u003c")
  );

  eleventyConfig.addFilter("limit", (arr, n) => (arr || []).slice(0, n));

  eleventyConfig.addFilter("sliceFrom", (arr, n) => (arr || []).slice(n));

  /** String split (Nunjucks has no built-in `split` filter). */
  eleventyConfig.addFilter("splitOn", (value, separator) =>
    String(value ?? "").split(separator)
  );


  eleventyConfig.addFilter("where", (arr, key, value) =>
    (arr || []).filter((item) => item[key] === value)
  );

  eleventyConfig.addFilter("slugify", (value) =>
    String(value)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "")
  );

  /**
   * Breadcrumb trail: Home / Category / Title.
   *
   * Takes explicit arguments rather than reading `page`, because Eleventy 3
   * does not merge front matter onto `page` and this Nunjucks build has no
   * context-filter support. Called from partials/breadcrumbs.njk, which has
   * the page's own data in scope.
   *
   * Each crumb carries `url` (relative, for the visible nav) and `item`
   * (absolute, for BreadcrumbList JSON-LD).
   */
  eleventyConfig.addFilter(
    "crumbItems",
    (categoryKey, title, categoryName) => {
      const siteUrl = require("./src/_data/site").url;
      const crumbs = [{ name: "Home", url: "/" }];
      if (categoryKey && categoryName) {
        crumbs.push({ name: categoryName, url: `/${categoryKey}/` });
      }
      crumbs.push({ name: title || "" });
      return crumbs.map((c) => (c.url ? { ...c, item: siteUrl + c.url } : { ...c }));
    }
  );

  /* ------------------------------------------------------------------ *
   * Shortcode: responsive, lazy, no-CLS image
   * ------------------------------------------------------------------ */
  eleventyConfig.addShortcode("postimage", function (src, alt, opts = {}) {
    const { ratio = "16/9", eager = false, sizes = "(min-width: 1040px) 320px, (min-width: 720px) 45vw, 92vw" } = opts;
    const [w, h] = ratio.split("/").map(Number);
    return `<img src="/assets/img/${src}" alt="${alt}" width="${1600}" height="${Math.round((1600 * h) / w)}" loading="${eager ? "eager" : "lazy"}" decoding="async" fetchpriority="${eager ? "high" : "auto"}" sizes="${sizes}" style="aspect-ratio:${ratio}">`;
  });

  /* ------------------------------------------------------------------ *
   * Markdown
   * ------------------------------------------------------------------ */
  eleventyConfig.setLibrary("md", (() => {
    const markdownIt = require("markdown-it");
    const md = markdownIt({
      html: true,
      linkify: true,
      typographer: true,
    });

    // External links: new tab + rel safety.
    const defaultRender =
      md.renderer.rules.link_open ||
      function (tokens, idx, options, env, self) {
        return self.renderToken(tokens, idx, options);
      };
    md.renderer.rules.link_open = function (tokens, idx, options, env, self) {
      const href = tokens[idx].attrGet("href") || "";
      if (/^https?:/.test(href)) {
        tokens[idx].attrSet("target", "_blank");
        tokens[idx].attrSet("rel", "noopener noreferrer nofollow");
      }
      return defaultRender(tokens, idx, options, env, self);
    };

    // Code blocks get a language class for optional highlighting later.
    const defaultFence = md.renderer.rules.fence;
    md.renderer.rules.fence = function (tokens, idx, options, env, self) {
      const lang = (tokens[idx].info || "").trim().split(/\s+/)[0];
      const out = defaultFence.call(this, tokens, idx, options, env, self);
      return lang ? out.replace("<pre>", `<pre data-lang="${lang}">`) : out;
    };

    return md;
  })());

  /**
   * Minify HTML on the way out. Collapses the whitespace that Nunjucks
   * leaves behind; safe for <pre> because it uses parse5-style tokenising
   * rather than a regex.
   */
  eleventyConfig.addTransform("htmlmin", function (content) {
    if (!this.page.outputPath || !this.page.outputPath.endsWith(".html")) {
      return content;
    }
    const { minify } = require("html-minifier-terser");
    return minify(content, {
      removeComments: true,
      collapseWhitespace: true,
      collapseBooleanAttributes: true,
      removeRedundantAttributes: true,
      removeScriptTypeAttributes: true,
      removeStyleLinkTypeAttributes: true,
      minifyCSS: false, // the inlined sheet is hand-formatted on purpose
      minifyJS: true,
    });
  });

  return {
    dir: { input: SRC, output: OUT, includes: "_includes", data: "_data" },
    templateFormats: ["md", "njk", "liquid", "html", "11ty.js"],
    /**
     * Markdown is treated as pure content — no template engine runs over the
     * body. This matters: code samples containing `{{ }}` (GitHub Actions,
     * Angular, Vue, Handlebars) would otherwise be parsed as template tags
     * and break the build. Interpolation belongs in the .njk templates.
     */
    markdownTemplateEngine: false,
    htmlTemplateEngine: "njk",
    pathPrefix: "/",
  };
};
